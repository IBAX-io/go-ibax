// Command extcallgen writes the typed calls of the extended functions of the VM: the
// constructors of script.ExtCall for the shapes of their signatures, in
// packages/script/extcall_gen.go, and the functions telling the call of each,
// scriptExtCall there and smart.ExtCallOf in packages/smart/extcall_gen.go. Run it, by go
// generate in packages/script, after adding an extended function of a new signature.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"github.com/IBAX-io/go-ibax/packages/script"
	"github.com/IBAX-io/go-ibax/packages/smart"
)

const (
	scriptPath = "github.com/IBAX-io/go-ibax/packages/script"
	smartPath  = "github.com/IBAX-io/go-ibax/packages/smart"
	// maxResults is the number of results an ExtCall returns
	maxResults = 3
	header     = "// Code generated by tools/extcallgen. DO NOT EDIT.\n\n"
)

// shape is the number of fixed parameters, whether the function is variadic and the number of
// results of a signature
type shape struct {
	params   int
	variadic bool
	results  int
}

func (s shape) name() string {
	v := ""
	if s.variadic {
		v = "V"
	}
	return fmt.Sprintf("ExtCall%d%sR%d", s.params, v, s.results)
}

var anySlice = reflect.TypeFor[[]any]()

// shapeOf is the shape of the function type t, false for one no ExtCall covers
func shapeOf(t reflect.Type) (shape, bool) {
	s := shape{params: t.NumIn(), variadic: t.IsVariadic(), results: t.NumOut()}
	if s.results > maxResults {
		return s, false
	}
	if s.variadic {
		if t.In(t.NumIn()-1) != anySlice {
			return s, false
		}
		s.params--
	}
	return s, true
}

// renderer writes the types of a package, collecting the imports they need
type renderer struct {
	self    string
	imports map[string]string
}

func (r *renderer) typ(t reflect.Type) (string, bool) {
	if t.Name() != "" {
		if t.PkgPath() == "" || t.PkgPath() == r.self {
			return t.Name(), true
		}
		pkg := t.PkgPath()[strings.LastIndex(t.PkgPath(), "/")+1:]
		r.imports[t.PkgPath()] = pkg
		return pkg + "." + t.Name(), true
	}
	switch t.Kind() {
	case reflect.Pointer:
		e, ok := r.typ(t.Elem())
		return "*" + e, ok
	case reflect.Slice:
		e, ok := r.typ(t.Elem())
		return "[]" + e, ok
	case reflect.Array:
		e, ok := r.typ(t.Elem())
		return fmt.Sprintf("[%d]%s", t.Len(), e), ok
	case reflect.Map:
		k, okk := r.typ(t.Key())
		e, oke := r.typ(t.Elem())
		return "map[" + k + "]" + e, okk && oke
	case reflect.Interface:
		if t.NumMethod() == 0 {
			return "any", true
		}
	}
	return "", false
}

// funcType writes the type of the function type t
func (r *renderer) funcType(t reflect.Type) (string, bool) {
	var in, out []string
	for i := 0; i < t.NumIn(); i++ {
		s, ok := r.typ(t.In(i))
		if !ok {
			return "", false
		}
		if t.IsVariadic() && i == t.NumIn()-1 {
			s = "..." + strings.TrimPrefix(s, "[]")
		}
		in = append(in, s)
	}
	for i := 0; i < t.NumOut(); i++ {
		s, ok := r.typ(t.Out(i))
		if !ok {
			return "", false
		}
		out = append(out, s)
	}
	ret := ""
	switch len(out) {
	case 0:
	case 1:
		ret = " " + out[0]
	default:
		ret = " (" + strings.Join(out, ", ") + ")"
	}
	return "func(" + strings.Join(in, ", ") + ")" + ret, true
}

// resolver writes the function name of package self telling the typed calls of funcs, adding the
// shapes it uses to shapes
func resolver(self, name, doc, qualifier string, funcs map[string]any, shapes map[shape]bool) (string, map[string]string) {
	r := &renderer{self: self, imports: map[string]string{}}
	cases := map[string]shape{}
	for _, fn := range funcs {
		t := reflect.TypeOf(fn)
		s, ok := shapeOf(t)
		if !ok {
			continue
		}
		sig, ok := r.funcType(t)
		if !ok {
			continue
		}
		cases[sig] = s
		shapes[s] = true
	}
	sigs := make([]string, 0, len(cases))
	for sig := range cases {
		sigs = append(sigs, sig)
	}
	sort.Strings(sigs)
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\nfunc %s(fn any) %sExtCall {\n\tswitch f := fn.(type) {\n", doc, name, qualifier)
	for _, sig := range sigs {
		fmt.Fprintf(&b, "\tcase %s:\n\t\treturn %s%s(f)\n", sig, qualifier, cases[sig].name())
	}
	b.WriteString("\t}\n\treturn nil\n}\n")
	return b.String(), r.imports
}

// constructor writes the constructor of ExtCall for the shape s
func constructor(s shape) string {
	var tparams, params, asserts, oks, call, rets []string
	for i := 0; i < s.params; i++ {
		tparams = append(tparams, fmt.Sprintf("A%d", i))
		params = append(params, fmt.Sprintf("A%d", i))
		asserts = append(asserts, fmt.Sprintf("\t\ta%d, ok%d := args[%d].(A%d)\n", i, i, i, i))
		oks = append(oks, fmt.Sprintf("!ok%d", i))
		call = append(call, fmt.Sprintf("a%d", i))
	}
	if s.variadic {
		params = append(params, "...any")
		call = append(call, "va...")
	}
	var results []string
	for i := 0; i < s.results; i++ {
		tparams = append(tparams, fmt.Sprintf("R%d", i))
		results = append(results, fmt.Sprintf("R%d", i))
		rets = append(rets, fmt.Sprintf("x%d", i))
	}
	ret := ""
	switch len(results) {
	case 0:
	case 1:
		ret = " " + results[0]
	default:
		ret = " (" + strings.Join(results, ", ") + ")"
	}
	argsName, vaName := "args", "va"
	if s.params == 0 {
		argsName = "_"
	}
	if !s.variadic {
		vaName = "_"
	}
	tp := ""
	if len(tparams) > 0 {
		tp = "[" + strings.Join(tparams, ", ") + " any]"
	}
	var b bytes.Buffer
	v := ""
	if s.variadic {
		v = " and variadic"
	}
	fmt.Fprintf(&b, "// %s is the ExtCall of a function of %d fixed parameters%s, and %d results\n",
		s.name(), s.params, v, s.results)
	fmt.Fprintf(&b, "func %s%s(f func(%s)%s) ExtCall {\n", s.name(), tp, strings.Join(params, ", "), ret)
	fmt.Fprintf(&b, "\treturn func(%s, %s []any) (r0, r1, r2 any, ok bool) {\n", argsName, vaName)
	for _, a := range asserts {
		b.WriteString(a)
	}
	if len(oks) > 0 {
		fmt.Fprintf(&b, "\t\tif %s {\n\t\t\treturn\n\t\t}\n", strings.Join(oks, " || "))
	}
	callExpr := "f(" + strings.Join(call, ", ") + ")"
	if s.results == 0 {
		fmt.Fprintf(&b, "\t\t%s\n\t\treturn nil, nil, nil, true\n", callExpr)
	} else {
		for len(rets) < maxResults {
			rets = append(rets, "nil")
		}
		fmt.Fprintf(&b, "\t\t%s := %s\n\t\treturn %s, true\n",
			strings.Join(rets[:s.results], ", "), callExpr, strings.Join(rets, ", "))
	}
	b.WriteString("\t}\n}\n")
	return b.String()
}

func writeFile(path, pkg string, imports map[string]string, body string) {
	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	if len(imports) > 0 {
		paths := make([]string, 0, len(imports))
		for p := range imports {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		b.WriteString("import (\n")
		for _, p := range paths {
			fmt.Fprintf(&b, "\t%q\n", p)
		}
		b.WriteString(")\n\n")
	}
	b.WriteString(body)
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("formatting %s: %v\n%s", path, err, b.String())
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// moduleRoot is the directory of go.mod above the working directory
func moduleRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		log.Fatal(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			log.Fatal("no go.mod above the working directory")
		}
		dir = parent
	}
}

func main() {
	root := moduleRoot()
	contractFuncs := map[string]any{}
	for v := range script.VMType_name {
		if script.VMType(v) == script.VMType_INVALID {
			continue
		}
		for name, fn := range smart.EmbedFuncs(script.VMType(v)) {
			contractFuncs[name] = fn
		}
	}
	shapes := map[shape]bool{}
	scriptBody, scriptImports := resolver(scriptPath, "scriptExtCall",
		"// scriptExtCall is the typed call of an extended function of the VM itself, nil for one of a\n"+
			"// signature no constructor of ExtCall covers",
		"", script.NewExtendData().Objects, shapes)
	smartBody, smartImports := resolver(smartPath, "ExtCallOf",
		"// ExtCallOf is the typed call of an extended function of contracts, nil for one of a signature\n"+
			"// no constructor of script.ExtCall covers",
		"script.", contractFuncs, shapes)
	smartImports[scriptPath] = "script"

	list := make([]shape, 0, len(shapes))
	for s := range shapes {
		list = append(list, s)
	}
	sort.Slice(list, func(i, j int) bool {
		a, b := list[i], list[j]
		if a.params != b.params {
			return a.params < b.params
		}
		if a.variadic != b.variadic {
			return !a.variadic
		}
		return a.results < b.results
	})
	var b strings.Builder
	for _, s := range list {
		b.WriteString(constructor(s))
		b.WriteString("\n")
	}
	b.WriteString(scriptBody)
	writeFile(filepath.Join(root, "packages/script/extcall_gen.go"), "script", scriptImports, b.String())
	writeFile(filepath.Join(root, "packages/smart/extcall_gen.go"), "smart", smartImports, smartBody)
}
