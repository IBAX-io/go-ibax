//go:generate go run ../../tools/extcallgen

// ExtCall calls an extended function with its arguments as the VM gathered them, without
// reflection. args are the values of the fixed parameters, those the VM passes by itself
// included, va the values of the variadic parameter of a variadic function. ok is false, and the
// function not called, when a value is not of the type of its parameter: the VM then calls the
// function by reflection, which converts the value as Go assigns it or panics as it did. r0, r1
// and r2 are the results of the function, as many as it returns.
//
// The constructors of ExtCall, ExtCall<parameters>[V]R<results>, are generated by
// tools/extcallgen for the signatures of the extended functions of the VM, with the functions
// telling the call of each: scriptExtCall here, smart.ExtCallOf for the functions of contracts.
type ExtCall func(args, va []any) (r0, r1, r2 any, ok bool)

// extCallFallbacks counts the calls an ExtCall refused for the types of their arguments
var extCallFallbacks atomic.Int64

var typeInt64 = reflect.TypeFor[int64]()

// extCallOf is the typed call of fn the extend data or the VM itself has, nil when neither has one
func extCallOf(ext *ExtendData, fn any) ExtCall {
	if ext.Calls != nil {
		if call := ext.Calls(fn); call != nil {
			return call
		}
	}
	return scriptExtCall(fn)
}

// ExtCallCoverage tells how many of the extended functions of the VM have a typed call, and the
// names of those that the VM calls by reflection
func (vm *VM) ExtCallCoverage() (covered, total int, reflected []string) {
	for name, obj := range vm.Objects {
		if obj.Type != ObjectType_ExtFunc {
			continue
		}
		total++
		if obj.GetExtFuncInfo().Call != nil {
			covered++
		} else {
			reflected = append(reflected, name)
		}
	}
	return
}

// extPars are the values the VM passes to reflect.Value.Call for a call of finfo: those of args,
// and the variadic one of va, or the zero value of its type when vaZero
func extPars(finfo *ExtFuncInfo, in int, args, va []any, vaZero bool) []reflect.Value {
	pars := make([]reflect.Value, in)
	for i, v := range args {
		pars[i] = reflect.ValueOf(v)
	}
	if vaZero {
		pars[in-1] = reflect.Zero(finfo.Params[in-1])
	} else if finfo.Variadic {
		pars[in-1] = reflect.ValueOf(va)
	}
	return pars
}

// callExtReflect calls finfo by reflection
func callExtReflect(finfo *ExtFuncInfo, pars []reflect.Value) []reflect.Value {
	foo := reflect.ValueOf(finfo.Func)
	if finfo.Variadic {
		return foo.CallSlice(pars)
	}
	return foo.Call(pars)
}

// extCost is the cost the first result r of finfo, a function querying the database, tells, as
// reflect.Value.Int gives it from a result of the type finfo declares
func extCost(finfo *ExtFuncInfo, r any) int64 {
	if finfo.Results[0] == typeInt64 {
		return r.(int64)
	}
	v := reflect.New(finfo.Results[0]).Elem()
	if r != nil {
		v.Set(reflect.ValueOf(r))
	}
	return v.Int()
}

// callExtend calls the extended function finfo with the count arguments of the stack of size
// values, for callFunc
func (rt *RunTime) callExtend(finfo *ExtFuncInfo, in, count, size int) (err error) {
	var (
		stack Stacker
		ok    bool
		limit = 0
	)
	if stack, ok = rt.extend[Extend_sc].(Stacker); ok {
		if err := stack.AppendStack(finfo.Name); err != nil {
			return err
		}
	}
	rt.extend[Extend_rt] = rt
	auto := 0
	for k := 0; k < in; k++ {
		if len(finfo.Auto[k]) > 0 {
			auto++
		}
	}
	shift := size - count + auto
	fixed := in
	if finfo.Variadic {
		shift = size - count
		count += auto
		limit = count - in + 1
		fixed = in - 1
	}
	// args are the values of the fixed parameters, in the buffer of the runtime: a function the
	// call runs takes the room after them
	base := len(rt.extArgs)
	rt.extArgs = append(rt.extArgs, make([]any, fixed)...)
	args := rt.extArgs[base : base+fixed : base+fixed]
	i := count
	for ; i > limit; i-- {
		var v any
		if len(finfo.Auto[count-i]) > 0 {
			v = rt.extend[finfo.Auto[count-i]]
			auto--
		} else {
			v = rt.stack[size-i+auto]
		}
		if v == nil {
			// the zero value of a string is what reflect.Value.Call got for nil
			v = ``
		}
		args[count-i] = v
	}
	var (
		va     []any
		vaZero bool
	)
	if i > 0 && size-i >= 0 {
		va = rt.stack[size-i : size]
	} else if finfo.Variadic {
		vaZero = true
	}
	if finfo.Name == `ExecContract` {
		if pars := extPars(finfo, in, args, va, vaZero); pars[2].Kind() != reflect.String || !pars[3].IsValid() {
			clear(rt.extArgs[base:])
			rt.extArgs = rt.extArgs[:base]
			return fmt.Errorf(`unknown function %v`, pars[1])
		}
	}
	var (
		r0, r1, r2 any
		called     bool
		result     []reflect.Value
	)
	if finfo.Call != nil {
		r0, r1, r2, called = finfo.Call(args, va)
		if !called {
			extCallFallbacks.Add(1)
		}
	}
	if !called {
		result = callExtReflect(finfo, extPars(finfo, in, args, va, vaZero))
	}
	clear(rt.extArgs[base:])
	rt.extArgs = rt.extArgs[:base]
	if shift < 0 {
		shift = 0
	}
	rt.resetByIdx(shift)
	if stack != nil {
		stack.PopStack(finfo.Name)
	}

	_, callsDB := rt.vm.FuncCallsDB[finfo.Name]
	if !called {
		for i, ret := range result {
			// first return value of every extend function that makes queries to DB is cost
			if callsDB && i == 0 {
				if err = rt.SubCost(ret.Int()); err != nil {
					return
				}
				continue
			}
			if finfo.Results[i].String() == `error` {
				if ret.Interface() != nil {
					rt.errInfo = ErrInfo{Name: finfo.Name}
					return ret.Interface().(error)
				}
			} else {
				rt.push(ret.Interface())
			}
		}
		return
	}
	results := [3]any{r0, r1, r2}
	for i := range finfo.Results {
		ret := results[i]
		// first return value of every extend function that makes queries to DB is cost
		if callsDB && i == 0 {
			if err = rt.SubCost(extCost(finfo, ret)); err != nil {
				return
			}
			continue
		}
		if finfo.Results[i].String() == `error` {
			if ret != nil {
				rt.errInfo = ErrInfo{Name: finfo.Name}
				return ret.(error)
			}
		} else {
			rt.push(ret)
		}
	}
	return
}

// callExtParams calls the extended function finfo with params, for VM.Call: all its results,
// an error among them, are the values it returns
func callExtParams(finfo *ExtFuncInfo, params []any) (ret []any) {
	in := len(finfo.Params)
	fixed := in
	if finfo.Variadic {
		fixed = in - 1
	}
	if finfo.Call != nil && len(params) >= fixed {
		var va []any
		if finfo.Variadic {
			va = params[fixed:]
		}
		if r0, r1, r2, ok := finfo.Call(params[:fixed], va); ok {
			results := [3]any{r0, r1, r2}
			for i := range finfo.Results {
				ret = append(ret, results[i])
			}
			return
		}
		extCallFallbacks.Add(1)
	}
	foo := reflect.ValueOf(finfo.Func)
	var result []reflect.Value
	pars := make([]reflect.Value, in)
	if finfo.Variadic {
		for i := 0; i < len(pars)-1; i++ {
			pars[i] = reflect.ValueOf(params[i])
		}
		pars[len(pars)-1] = reflect.ValueOf(params[len(pars)-1:])
		result = foo.CallSlice(pars)
	} else {
		for i := 0; i < len(pars); i++ {
			pars[i] = reflect.ValueOf(params[i])
		}
		result = foo.Call(pars)
	}
	for _, iret := range result {
		ret = append(ret, iret.Interface())
	}
	return
}
